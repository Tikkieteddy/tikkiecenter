import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const rootDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageJson = JSON.parse(readFileSync(resolve(rootDirectory, "package.json"), "utf8"));
const semanticVersionPattern = /^(\d+)\.(\d+)\.(\d+)$/;
const versionMatch = semanticVersionPattern.exec(packageJson.version);

if (!versionMatch) {
  throw new Error(`package.json version must use MAJOR.MINOR.PATCH, received: ${packageJson.version}`);
}

const buildTime = new Date();
const bangkokDateParts = Object.fromEntries(
  new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Bangkok",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  })
    .formatToParts(buildTime)
    .filter(({ type }) => type !== "literal")
    .map(({ type, value }) => [type, value]),
);

const buildDate = `${bangkokDateParts.year}${bangkokDateParts.month}${bangkokDateParts.day}`;
const bangkokDayStart = new Date(
  `${bangkokDateParts.year}-${bangkokDateParts.month}-${bangkokDateParts.day}T00:00:00+07:00`,
);
const bangkokDayEnd = new Date(bangkokDayStart.getTime() + 24 * 60 * 60 * 1000);

function positiveInteger(value) {
  const parsed = Number.parseInt(value ?? "", 10);
  return Number.isInteger(parsed) && parsed > 0 ? parsed : null;
}

function resolveBuildRound() {
  const configuredRound = positiveInteger(process.env.BUILD_ROUND);

  if (configuredRound) {
    return configuredRound;
  }

  try {
    const commitCount = execFileSync(
      "git",
      [
        "rev-list",
        "--count",
        `--since=${bangkokDayStart.toISOString()}`,
        `--until=${bangkokDayEnd.toISOString()}`,
        "HEAD",
      ],
      { cwd: rootDirectory, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    );

    return positiveInteger(commitCount.trim()) ?? 1;
  } catch {
    return 1;
  }
}

const majorVersion = versionMatch[1];
const buildRound = resolveBuildRound();
const currentYear = Number.parseInt(bangkokDateParts.year, 10);
const copyrightYears = currentYear > 2026 ? `2026-${currentYear}` : "2026";
const buildInfo = {
  semanticVersion: packageJson.version,
  majorVersion,
  shortVersion: `V.${majorVersion}`,
  fullVersion: `V.${packageJson.version}+${buildDate}.${buildRound}`,
  buildDate,
  buildRound,
  copyrightYears,
};

const outputPath = resolve(rootDirectory, "src/generated/build-info.ts");
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(
  outputPath,
  `// Generated by scripts/generate-build-info.mjs. Do not edit manually.\nexport const buildInfo = ${JSON.stringify(buildInfo, null, 2)} as const;\n`,
  "utf8",
);

process.stdout.write(`Generated ${buildInfo.fullVersion}\n`);
